async function applySourcePatches(workdir, templateId) {
  for (const patch of SOURCE_PATCHES[templateId] ?? []) {
    const target = path.join(workdir, patch.file);

    if (patch.contents !== undefined) {
      if (await exists(target)) {
        throw new Error(
          `${patch.file} is now in the scaffolded tree, so this bake would overwrite`
          + ' whatever the scaffolder decided it should hold',
        );
      }
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, patch.contents);
      process.stdout.write(`bake:templates — ${templateId}: added ${patch.file}\n`);
      continue;
    }

    if (!(await exists(target))) {
      throw new Error(`${patch.file} is not in the scaffolded tree, so this bake cannot patch it`);
    }
    const before = await readFile(target, 'utf8');
    if (!before.includes(patch.find)) {
      throw new Error(
        `${patch.file} no longer contains the text this bake patches, so the correction`
        + ` would silently stop being applied. Expected to find:\n${patch.find}`,
      );
    }
    await writeFile(target, before.replace(patch.find, patch.replace));
    process.stdout.write(`bake:templates — ${templateId}: patched ${patch.file}\n`);
  }
}

/** What the scaffolder's own install actually resolved each package to. */
async function readLockedVersions(workdir) {
  const versions = new Map();
  try {
    const lock = JSON.parse(await readFile(path.join(workdir, 'package-lock.json'), 'utf8'));
    for (const [key, entry] of Object.entries(lock.packages ?? {})) {
      const name = key.startsWith('node_modules/') ? key.slice('node_modules/'.length) : '';
      if (name && !name.includes('/node_modules/') && entry?.version) {
        versions.set(name, entry.version);
      }
    }
  } catch {
    // No lockfile, so nothing to read a resolved version from. Floating ranges
    // stay as they are rather than being pinned to a guess.
  }
  return versions;
}

/**
 * Close the two gaps a scaffolder leaves in a tree that is about to be frozen:
 * ranges that float, and versions that this platform cannot build.
 *
 * The lockfile is rewritten afterwards rather than edited, because the point of
 * the exercise is a lockfile that agrees with its manifest — leaving the one the
 * scaffolder wrote in place would reproduce the problem being fixed.
 */
async function alignDependencies(workdir, templateId) {
  const manifestFile = path.join(workdir, 'package.json');
  const manifest = JSON.parse(await readFile(manifestFile, 'utf8'));
  const locked = await readLockedVersions(workdir);
  const pins = DEPENDENCY_PINS[templateId] ?? {};
  const changes = [];

  for (const field of ['dependencies', 'devDependencies']) {
    const pinned = pins[field] ?? {};
    if (!manifest[field] && Object.keys(pinned).length === 0) continue;
    const block = { ...manifest[field] };

    for (const [name, range] of Object.entries(block)) {
      if (name in pinned || !FLOATING_RANGE.test(range)) continue;
      const resolved = locked.get(name);
      if (!resolved) continue;
      block[name] = `^${resolved}`;
      changes.push(`${name} ${range} -> ^${resolved}`);
    }
    for (const [name, range] of Object.entries(pinned)) {
      // A null range drops the package. Only reachable for one a patch above
      // has just made unreachable from source, so the install it costs is
      // wasted and the name it leaves behind is misleading.
      if (range === null) {
        if (!(name in block)) continue;
        changes.push(`${name} ${block[name]} -> (removed)`);
        delete block[name];
        continue;
      }
      if (block[name] === range) continue;
      changes.push(`${name} ${block[name] ?? '(absent)'} -> ${range}`);
      block[name] = range;
    }

    manifest[field] = Object.fromEntries(
      Object.entries(block).sort(([a], [b]) => a.localeCompare(b)),
    );
  }

  // The same correction one level up. A scaffolder writes the engine floor the
  // dependency it chose demands, so pinning that dependency back to what this
  // platform runs strands the floor above it: the template then declares a Node
  // it no longer needs, and every install under the sandbox's own version opens
  // with an EBADENGINE warning about a requirement nothing in the tree has.
  for (const [name, range] of Object.entries(pins.engines ?? {})) {
    const current = manifest.engines?.[name];
    if (current === range) continue;
    changes.push(`engines.${name} ${current ?? '(absent)'} -> ${range}`);
    manifest.engines = { ...manifest.engines, [name]: range };
  }

  if (changes.length === 0) return;
  await writeFile(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`);
  for (const change of changes) {
    process.stdout.write(`bake:templates — ${templateId}: pinned ${change}\n`);
  }

  const lockfile = path.join(workdir, 'package-lock.json');
  if (!(await exists(lockfile))) return;

  // Deleted rather than updated, which is what "rewritten" above has to mean.
  // npm reads an existing lockfile as the tree to reconcile against, and after
  // a pin that moves a major the old one describes a graph the new manifest
  // contradicts — react-router 7 against the scaffolder's 8 disagrees on peers
  // the whole way down, and npm stops at the conflict rather than resolving
  // past it. There is nothing in the old graph this wants to keep.
  await rm(lockfile, { force: true });

  // --ignore-scripts because this resolves a graph rather than building a
  // tree. node_modules left with the other build artifacts before this ran, so
  // an install hook firing here runs against binaries that are no longer on
  // disk: Nuxt's `postinstall: nuxt prepare` exits 127 on the missing `nuxt`,
  // and SvelteKit's `prepare` survived the same call only because it happens
  // to end in `|| echo ''`.
  await run('npm', ['install', '--package-lock-only', '--ignore-scripts', '--no-audit', '--no-fund'], {
    cwd: workdir,
    maxBuffer: 64 * 1024 * 1024,
  });
}

/** The single fenced command under a reference's `## Scaffold` heading. */
function extractScaffoldCommand(markdown) {
  return extractFencedCommand(markdown, 'Scaffold');
}

/** The single fenced command under one of a reference's headings. */
function extractFencedCommand(markdown, heading) {
  const section = markdown.match(
    new RegExp(String.raw`^## ${heading}\s*$([\s\S]*?)(?=^## |\Z)`, 'm'),
  )?.[1];
  if (!section) return null;
  const blocks = [...section.matchAll(/```(?:bash|sh|shell)\n([\s\S]*?)```/g)];
  // Exactly one, or this script would be choosing on the reference's behalf —
  // which is the drift the manifest check exists to prevent.
  if (blocks.length !== 1) return null;
  const command = blocks[0][1].trim();
  return command.includes('\n') || !RUNS_UNATTENDED.test(command) ? null : command;
}

/**
 * Frameworks that ship no scaffolder, documented outside makers-frameworks.
 *
 * The agent frameworks are the platform's own reason to exist and had no baked
 * tree at all, so every run that named one opened on an empty workspace: a
 * measured DeepAgents session spent 145 seconds reading references and
 * deliberating before the first package.json existed, which is also the first
 * moment the install can start.
 *
 * There is nothing to scaffold — no `create-deepagents` exists — but the
 * expensive half was never the file layout. It was arriving at a set of
 * versions that resolve: the same session lost another 46 seconds to an
 * ERESOLVE, two registry probes, and a second install. So the `npm install`
 * line the reference documents *is* the command, run here once against a
 * lockfile, and SOURCE_PATCHES supplies the handful of files npm does not
 * write. The reference stays the source of truth either way — the manifest
 * records what ran, and a test fails when the two drift apart.
 */
const SCAFFOLDERLESS_TEMPLATES = [
  { id: 'deepagents', ref: 'makers-agents/references/node-frameworks/deepagents.md', heading: 'Dependencies' },
  { id: 'langgraph', ref: 'makers-agents/references/node-frameworks/langgraph.md', heading: 'Dependencies' },
];

/** A reference under makers-frameworks, or a path from the skills root. */
function referenceFile(ref) {
  return ref.includes('/') ? path.join(skillsDir, ref) : path.join(referencesDir, ref);
}

async function bakeableTemplates() {
  const entries = await readdir(referencesDir, { withFileTypes: true });
  const found = [];
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.md')) continue;
    const markdown = await readFile(path.join(referencesDir, entry.name), 'utf8');
    const command = extractScaffoldCommand(markdown);
    if (command) {
      found.push({ id: entry.name.replace(/\.md$/, ''), ref: entry.name, command });
    }
  }
  for (const { id, ref, heading } of SCAFFOLDERLESS_TEMPLATES) {
    const markdown = await readFile(referenceFile(ref), 'utf8');
    const command = extractFencedCommand(markdown, heading);
    // Loudly, unlike the scan above: this one is named here by hand, so a
    // reference that stopped carrying a single-line command is an edit that
    // silently dropped a template rather than a framework we never baked.
    if (!command) {
      throw new Error(`${ref} has no single-line command under ## ${heading}, so ${id} cannot be baked`);
    }
    found.push({ id, ref, command });
  }
  found.sort((a, b) => a.id.localeCompare(b.id));
  return found;
}

async function exists(target) {
  try {
    await stat(target);
    return true;
  } catch {
    return false;
  }
}

async function pruneArtifacts(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const target = path.join(dir, entry.name);
    if (NOT_PART_OF_THE_TEMPLATE.has(entry.name)) {
      await rm(target, { recursive: true, force: true });
    } else if (entry.isDirectory()) {
      await pruneArtifacts(target);
    } else if (entry.name === '.gitignore') {
      const stored = path.join(dir, GITIGNORE_STORED_AS);
      if (await exists(stored)) {
        throw new Error(`${stored} already exists, so the .gitignore beside it cannot be stored`);
      }
      await rename(target, stored);
    }
  }
}

async function measure(dir) {
  let files = 0;
  let bytes = 0;
  async function walk(current) {
    for (const entry of await readdir(current, { withFileTypes: true })) {
      const target = path.join(current, entry.name);
      if (entry.isDirectory()) {
        await walk(target);
      } else {
        files += 1;
        bytes += (await stat(target)).size;
      }
    }
  }
  await walk(dir);
  return { files, bytes };
}

/**
 * The directory a scaffolder runs in, which is also the name it gives the
 * project: every one of them derives `package.json`'s name field from the
 * basename, and mkdtemp's random suffix carries capitals that npm rejects
 * outright — create-next-app stops with "name can no longer contain capital
 * letters" before it writes anything.
 *
 * `app` rather than the template id, because that is the basename the sandbox
 * would have handed the scaffolder anyway: appDir ends in /app. Baking under
 * the same name is what keeps the template identical to the tree the run it
 * replaces would have produced.
 */
const SCAFFOLD_DIRECTORY_NAME = 'app';

async function bake(template) {
  const scratch = await mkdtemp(path.join(os.tmpdir(), `bake-${template.id}-`));
  const workdir = path.join(scratch, SCAFFOLD_DIRECTORY_NAME);
  await mkdir(workdir, { recursive: true });
  const destination = path.join(templatesDir, template.id);
  try {
    process.stdout.write(`bake:templates — ${template.id}: ${template.command}\n`);
    // The scaffolders want an empty directory and say so; the sandbox gives
    // them one, and so does this.
    await run('sh', ['-c', template.command], {
      cwd: workdir,
      maxBuffer: 64 * 1024 * 1024,
      env: { ...process.env, CI: '1', ADBLOCK: '1', DISABLE_OPENCOLLECTIVE: '1' },
    });

    await pruneArtifacts(workdir);

    // "It wrote something" is not the same as "it scaffolded a project", and
    // the difference is the failure this guard exists for: `sv create` exits 0
    // after leaving behind a .npmrc and a .gitignore when it cannot reach its
    // template, and a two-file template baked from that would have shipped as a
    // framework the agent believes it can start a project from. Every scaffolder
    // here is an npm one, so a root package.json is the thing that separates a
    // project from a pair of dotfiles.
    if (!(await exists(path.join(workdir, 'package.json')))) {
      throw new Error(
        'the scaffolder exited cleanly without writing a package.json, so it never'
        + ' scaffolded anything — check whether it fetches its template over the network',
      );
    }
    await applySourcePatches(workdir, template.id);
    await alignDependencies(workdir, template.id);

    const { files, bytes } = await measure(workdir);

    await rm(destination, { recursive: true, force: true });
    await cp(workdir, destination, { recursive: true });

    const kb = Math.round(bytes / 1024);
    process.stdout.write(`bake:templates — ${template.id}: ${files} files, ${kb}KB\n`);
    return { ...template, files, bytes, bakedAt: new Date().toISOString().slice(0, 10) };
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
}

async function readManifest() {
  try {
    return JSON.parse(await readFile(manifestPath, 'utf8'));
  } catch {
    return { templates: [] };
  }
}

const requested = process.argv.slice(2);
const available = await bakeableTemplates();

if (requested.includes('--list')) {
  for (const template of available) {
    process.stdout.write(`${template.id.padEnd(16)} ${template.command}\n`);
  }
  process.exit(0);
}

const selected = requested.length
  ? available.filter((template) => requested.includes(template.id))
  : available;

if (selected.length === 0) {
  const names = available.map((template) => template.id).join(', ');
  console.error(`bake:templates — nothing to bake. Available: ${names}`);
  process.exit(1);
}

const existing = await readManifest();
const baked = new Map(existing.templates.map((template) => [template.id, template]));
const failures = [];

for (const template of selected) {
  try {
    baked.set(template.id, await bake(template));
  } catch (error) {
    // One framework's scaffolder being down, renamed, or newly interactive must
    // not throw away the templates that did bake — the manifest is written
    // either way, and the summary says what is missing from it.
    //
    // Its own output is the whole diagnosis, and a scaffolder says why it
    // stopped on the stream execFile does not put in `message`. Trimming that
    // to the first line once cost an afternoon on a conflicting-directory
    // notice that was sitting in stderr the entire time.
    failures.push(template.id);
    const detail = [error.stderr, error.stdout, error.message]
      .find((stream) => typeof stream === 'string' && stream.trim());
    console.error(`bake:templates — ${template.id} failed:\n${(detail || '').trimEnd()}`);
  }
}

await writeFile(
  manifestPath,
  `${JSON.stringify(
    {
      bakedWith: { node: process.version },
      templates: [...baked.values()].sort((a, b) => a.id.localeCompare(b.id)),
    },
    null,
    2,
  )}\n`,
);

process.stdout.write(`bake:templates — manifest lists ${baked.size} templates\n`);
if (failures.length) {
  console.error(`bake:templates — did not bake: ${failures.join(', ')}`);
  process.exit(1);
}
