/**
 * Run the official scaffolders once, here, so that no conversation has to.
 *
 * A new project used to reach its first file four round trips and a package
 * download later: ensure_project_scaffold, load_makers_skill for the framework
 * reference, then `npx create-next-app@latest` — which fetches the create
 * package, fetches a template, and installs as it goes. All of it produces the
 * same tree every time, and none of it depends on the request.
 *
 * So it happens at bake time instead. What lands in templates/ is the
 * scaffolder's own output, byte for byte, minus the directories no project
 * needs carried around; the agent writes it into the sandbox in one command and
 * starts the install in the same breath.
 *
 * The command is not written down here. It lives in the framework reference the
 * agent already loads, this script parses it out of there, and the manifest
 * records which command produced which tree so a skill sync that changes a
 * scaffolder fails the test instead of silently leaving a stale template.
 *
 * Usage:
 *   node scripts/bake-templates.mjs             # every bakeable framework
 *   node scripts/bake-templates.mjs nextjs      # just this one
 *   node scripts/bake-templates.mjs --list      # what could be baked, and how
 */

